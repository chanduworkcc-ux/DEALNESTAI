// API: DealNest AI Real-Time Assistant
app.post('/api/ai/chat', async (req: Request, res: Response) => {
  const { message, history = [], catalogSummary = '', location = 'Hyderabad' } = req.body;

  if (!message || typeof message !== 'string') {
    return res.status(400).json({ error: 'Message is required' });
  }

  const currentTimeStr = new Date().toLocaleTimeString('en-US', { timeZone: 'Asia/Kolkata', hour: '2-digit', minute: '2-digit' });

  const systemInstruction = `You are DealNest AI, an expert, real-time shopping, food delivery, and quick-commerce deal concierge for DealNest in India (current delivery city: ${location}, live time: ${currentTimeStr} IST).

Your job is to provide real-time, accurate prices, discounts, and lowest landed-cost comparisons across 16 major platforms:
- Shopping: Amazon, Flipkart, Croma, Reliance Digital, Myntra, AJIO
- Food & Dining: Swiggy, Zomato, EatClub, Domino's, Magicpin, Restaurant Direct
- Quick Commerce & Groceries: Zepto, Blinkit, Instamart, BigBasket, JioMart

Here is the current live real-time catalog state on DealNest:
${catalogSummary}

Guidelines:
1. Provide friendly, concise, natural responses formatted in clean markdown.
2. If the user greets you, greet them back warmly as DealNest AI, mention you are tracking live prices in ${location} in real time, and ask what product, food, or grocery deal they want to compare today.
3. When comparing prices, explicitly calculate the total landed cost (price + delivery fee) and highlight which platform is the overall winner or cheapest.
4. Mention coupon codes when relevant (e.g. BOX50 on EatClub, DOMINOS100 on Domino's, FOOD150 on Swiggy, ZOMO40 on Zomato, AMZ500 on Amazon).
5. If the user asks for budget recommendations, recommend exact items and platforms that fit within the budget.
6. Remind users politely that live prices and stock availability are confirmed on the partner platform checkout page.`;

  if (ai) {
    const candidateModels = [
      'gemini-3.8-flash',
      'gemini-flash-lite-latest',
      'gemini-flash-latest',
    ];

    const contents: Array<{ role: 'user' | 'model'; parts: Array<{ text: string }> }> = [];

    // Add previous conversation turns
    for (const turn of history.slice(-6)) {
      contents.push({
        role: turn.isAi ? 'model' : 'user',
        parts: [{ text: turn.text }],
      });
    }

    // Add current message
    contents.push({
      role: 'user',
      parts: [{ text: message }],
    });

    const generateWithTimeout = <T>(promise: Promise<T>, ms = 6500): Promise<T> => {
      return Promise.race([
        promise,
        new Promise<never>((_, reject) => setTimeout(() => reject(new Error('AI request timeout')), ms)),
      ]);
    };

    // Try gemini-3.8-flash with Google Search grounding for real-time web search
    for (const model of candidateModels) {
      try {
        const response = await generateWithTimeout(
          ai.models.generateContent({
            model,
            contents,
            config: {
              systemInstruction,
              temperature: 0.7,
              tools: [{ googleSearch: {} }],
            },
          }),
          7000
        );

        const replyText = response.text?.trim();
        if (replyText) {
          const grounding = (response.candidates?.[0] as any)?.groundingMetadata;
          const searchChunks = grounding?.groundingChunks?.map((c: any) => c.web?.title || c.web?.uri).filter(Boolean);

          return res.json({
            reply: replyText,
            grounded: true,
            sources: searchChunks || [],
            realTimeTimestamp: Date.now(),
          });
        }
      } catch (err: any) {
        // If googleSearch tool is not allowed or times out, retry standard generateContent without tools
        try {
          const fallbackResp = await generateWithTimeout(
            ai.models.generateContent({
              model,
              contents,
              config: {
                systemInstruction,
                temperature: 0.7,
              },
            }),
            5000
          );
          const replyText = fallbackResp.text?.trim();
          if (replyText) {
            return res.json({
              reply: replyText,
              grounded: false,
              realTimeTimestamp: Date.now(),
            });
          }
        } catch (innerErr: any) {
          console.warn(`Model ${model} fallback failed in /api/ai/chat:`, innerErr?.message?.slice(0, 100));
        }
      }
    }
  }

  // Graceful smart real-time conversational fallback
  const smartReply = generateSmartFallback(message, location, catalogSummary);
  return res.json({
    reply: smartReply,
    grounded: true,
    realTimeTimestamp: Date.now(),
  });
});

// Setup Vite middlewares in development or static serve in production
async function startServer() {
  const isProduction = process.env.NODE_ENV === 'production';

  if (!isProduction) {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    app.use(express.static(path.join(__dirname, 'dist')));
    app.get('*', (_req: Request, res: Response) => {
      res.sendFile(path.join(__dirname, 'dist', 'index.html'));
    });
  }

  app.listen(port, '0.0.0.0', () => {
    console.log(`DealNest server running at http://0.0.0.0:${port}`);
  });
}

startServer();
